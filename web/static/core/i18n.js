export function selectLocale(preference, browserLanguages) {
  if (preference === 'en' || preference === 'de') return preference;
  for (const language of browserLanguages) {
    const primary = language.toLowerCase().split('-')[0];
    if (primary === 'en' || primary === 'de') return primary;
  }
  return 'en';
}

export const locale = selectLocale(
  localStorage.getItem('labdash.language'),
  navigator.languages?.length ? navigator.languages : [navigator.language],
);

export function t(message, ...values) {
  const template = locale === 'de' ? de[message] ?? message : message;
  return template.replace(/\{(\d+)\}/g, (_, index) => values[index]);
}

export function localizePage(root) {
  root.documentElement.lang = locale;
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.textContent);
  for (const el of root.querySelectorAll('[data-i18n-attrs]')) {
    for (const attr of el.dataset.i18nAttrs.split(' ')) el.setAttribute(attr, t(el.getAttribute(attr)));
  }
}
